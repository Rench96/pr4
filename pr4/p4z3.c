#include <stdio.h>

int main(void)
{
    int n;
    int i = 0;
    unsigned long long a = 1;

    printf("Сколько элементов вывести? ");
    scanf("%d", &n);

    // i++ (постфиксный) сначала отдаёт старое значение i, а потом увеличивает его на 1.
    // ++i (префиксный) сначала увеличивает i, а потом отдаёт уже новое значение.
    // Здесь нужен именно i++: сравнивается старое i (0, 1, 2 ...), поэтому цикл
    // выполнится ровно n раз. С ++i цикл выполнился бы на один раз меньше.
    while (i++ < n)
    {
        printf("%llu ", a);
        a = a * 1000;
    }
    printf("\n");
    return 0;
}